"""Turn a compiled Model into a self-contained Blender build.py (engine inlined, Alt+P to run)."""
import inspect
import os
from pathlib import Path

from . import shapes
from .core import build_model

HERE = Path(__file__).parent


def _call(op):
    a = list(op.args)
    pos = ', '.join(str(v) for v in a[:-1]) + f", '{a[-1]}'"
    kw = ''.join(f', {k}={v!r}' for k, v in op.kwargs.items())
    return f'{op.fn}(V, {pos}{kw})'


def _thin(spec, spec_c, palette, extras, body, size, metal, d):
    rel = os.path.relpath(HERE / 'engine_blender.py', d.resolve())
    nl = chr(10)
    return f"""# {spec.name} ({spec.id}) -- GENERATED by voxel-sdk (thin). Do not edit: change layout.toml, run `voxel-sdk build`.
# Loads the engine from the SDK checkout; use `voxel-sdk build --standalone` for a file that needs nothing else.
#
# ---- spec.md ----
{spec_c}
import os
try:
    _here = os.path.dirname(os.path.abspath(__file__))
except NameError:
    _here = {str(d.resolve())!r}
exec(open(os.path.normpath(os.path.join(_here, {rel!r}))).read())
{extras + nl if extras else ''}
{palette}
C = {{**PALETTE}}
V = Grid()
{nl.join(body)}
R = build('{spec.name}', V, C, size={size}, grain={spec.grain:g}{metal})
result = {{k: R[k] for k in ('object', 'voxels', 'height_m', 'warnings')}}
"""


def render(element_dir, standalone=False):
    """Returns (build.py text, Report). Raises ValueError if the model has errors.
    Thin (default): the engine is exec'd from the SDK checkout. standalone=True inlines it (shareable without the repo)."""
    d = Path(element_dir)
    model = build_model(d)
    if not model.report.ok:
        raise ValueError('cannot build, fix errors first:\n' + '\n'.join(model.report.errors))
    spec = model.spec
    spec_c = '\n'.join('#   ' + l if l else '#' for l in spec.text.splitlines())
    palette = 'PALETTE = ' + repr(model.palette)
    need = {o.fn for o in model.ops} | {n for o in model.ops if o.code for n in ('shell', 'ellipse') if n in o.code}
    extras = '\n\n'.join(inspect.getsource(f).rstrip() for f in (shapes.shell, shapes.ellipse) if f.__name__ in need)
    body = []
    for op in model.ops:
        if op.code is not None:
            body += [f'# {op.part} (raw block)', op.code.strip('\n')]
        else:
            body += [f'# {op.part} ({op.key})', _call(op)]
    used = set(model.grid.keys)
    size = 'FINE_SIZE' if spec.grid == 'F' else 'VOXEL_SIZE'
    metal = ", metallic=('metal',)" if 'metal' in used else ''
    bar = '# ' + '=' * 70
    if not standalone:
        return _thin(spec, spec_c, palette, extras, body, size, metal, d), model.report
    out = f"""# {spec.name} ({spec.id}) -- fully self-contained Blender script.
# GENERATED by voxel-sdk from spec.md + layout.toml. Do not edit: change layout.toml and rebuild.
# Usage: Blender > Scripting workspace > Open this file > Run Script (Alt+P).
# Needs Blender 4.x/5.x (bundled numpy). No other files needed.
#
# ---- spec.md (design intent) ----
{spec_c}

{bar}
# 1. VOXEL ENGINE (grid, shapes, greedy meshing, materials, export)
{bar}
{(HERE / 'engine_blender.py').read_text().rstrip()}


# SDK extra shapes
{extras}


{bar}
# 2. COLOUR PALETTE (linear RGB 0-1)
{bar}
{palette}


{bar}
# 3. MODEL: {spec.name} (generated from layout.toml)
{bar}
C = {{**PALETTE}}
V = Grid()
{chr(10).join(body)}
R = build('{spec.name}', V, C, size={size}, grain={spec.grain:g}{metal})
result = {{k: R[k] for k in ('object', 'voxels', 'height_m', 'warnings')}}
"""
    compile(out, 'build.py', 'exec')
    return out, model.report


def write_build(element_dir, standalone=False):
    text, report = render(element_dir, standalone)
    (Path(element_dir) / 'build.py').write_text(text)
    return report
