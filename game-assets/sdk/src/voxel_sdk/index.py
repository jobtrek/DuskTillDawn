"""voxel-sdk index [--check]: rebuild game-assets/INDEX.md from every game-assets/t*/*/spec.md."""
import re
from pathlib import Path

from .rules import MAX_LINES, lint_spec

GAME_ASSETS = Path(__file__).resolve().parents[3]
INDEX = GAME_ASSETS / 'INDEX.md'
TIERS = {'T1': 'Tiny (up to 15 cm)', 'T2': 'Small (15-60 cm)', 'T3': 'Medium (60 cm-1.3 m)',
         'T4': 'Large (over 1.3 m)', 'T5': 'Rooms (grid S, collider on, grain 0)',
         'T6': 'Building (grid S, collider on, grain 0)'}
HEADER = """# Element index

Generated by `uv run voxel-sdk index` from every `spec.md`. Never edit by hand: change the Spec and regenerate.
Priority: **V1** = needed for the first playable. **UP** = needed when that upgrade is bought.
"""


def load(path):
    text = path.read_text()
    fm, key = {}, None
    for line in text.split('---')[1].strip().splitlines():
        if line.startswith('  ') and key:
            k, v = line.strip().split(': ', 1)
            fm[key][k] = v
        else:
            k, _, v = line.partition(':')
            key = k.strip()
            fm[key] = v.strip() if v.strip() else {}
    parts = {'1': [], '2': [], '3': [], '2/3': []}
    for m in re.finditer(r'^- \[(1|2|3|2/3)\] (.*)$', text, re.M):
        parts[m.group(1)].append(re.split(r':| \d', m.group(2))[0])  # drop cm sizes
    fm['_parts'], fm['_path'] = parts, path.relative_to(GAME_ASSETS)
    return fm


def _size(fm):
    return f"{fm['size_cm'].replace('x', '×')} → {fm['voxels'].replace('x', '×')}"


def _link(fm):
    return f"[{fm['id']}]({fm['_path'].as_posix()})"


def _row_small(fm):
    states = fm['states'] if isinstance(fm.get('states'), dict) else fm.get('pieces', {})
    st = ', '.join('_' + s for s in states) or 'one'
    p = fm['_parts']
    detail = ', '.join(p['2']) + ' · ' + ', '.join(p['3'])
    return f"| {_link(fm)} | **{fm['name']}** | {fm['room']} | {_size(fm)} | {fm['grid']} | {st} | {detail} | {fm['priority']} |"


def _row_room(fm):
    pieces = fm['pieces'] if isinstance(fm.get('pieces'), str) else 'one'
    return f"| {_link(fm)} | **{fm['name']}** | {fm['room']} | {_size(fm)} | {pieces} | {', '.join(fm['_parts']['2/3'])} | {fm['priority']} |"


def render(fms):
    out = [HEADER]
    for tier, title in TIERS.items():
        rows = [f for f in fms if f['tier'] == tier]
        if tier in ('T5', 'T6'):
            head = ['| ID | Element | Where | Size cm → voxels (W×D×H) | Pieces | Detail | Pri |', '|---|---|---|---|---|---|---|']
            body = [_row_room(f) for f in rows]
        else:
            head = ['| ID | Element | Room | Size cm → voxels (W×D×H) | Grid | States / pieces (separate models) | Secondary · tertiary detail | Pri |',
                    '|---|---|---|---|---|---|---|---|']
            body = [_row_small(f) for f in rows]
        out.append(f'## {tier}: {title}\n\n' + '\n'.join(head + body) + '\n')
    return '\n'.join(out)


def run(check=False, root=GAME_ASSETS):
    specs = sorted(Path(root).glob('t*/*/spec.md'))
    fms = sorted((load(p) for p in specs), key=lambda f: f['id'])
    errors, warnings = [], []
    for p in specs:
        e, w = lint_spec(p)
        errors += [f'{p.parent.name}: {m}' for m in e]
        warnings += [f'{p.parent.name}: {m}' for m in w]
    new = render(fms)
    if check:
        if not INDEX.exists() or INDEX.read_text() != new:
            errors.append('game-assets/INDEX.md is stale, run: uv run voxel-sdk index')
    else:
        INDEX.write_text(new)
    if warnings:
        worst = sorted(warnings, key=lambda w: -int(w.split(': ')[1].split()[0]))[:5]
        print(f'{len(warnings)} specs over {MAX_LINES} lines, worst: ' + '; '.join(worst))
    print('\n'.join(errors) or f'ok: {len(fms)} specs')
    return 1 if errors else 0
